/**
 * Localizes a scheme object based on the active language code
 * @param {Object} scheme - Base scheme object
 * @param {string} langCode - Language code, e.g. 'kn', 'ta', 'hi', 'ml', 'te', 'en'
 * @returns {Object} Localized scheme object
 */
export function getLocalizedScheme(scheme, langCode = 'en') {
  if (!scheme || !scheme.id) return scheme;
  if (!langCode || langCode === 'en') return scheme;

  const schemeTrans = SCHEME_TRANSLATIONS[scheme.id]?.[langCode];
  if (!schemeTrans) return scheme;

  return {
    ...scheme,
    name: schemeTrans.name || scheme.name,
    shortName: schemeTrans.shortName || scheme.shortName,
    department: schemeTrans.department || scheme.department,
    nodalAgency: schemeTrans.nodalAgency || scheme.nodalAgency,
    sector: schemeTrans.sector || scheme.sector,
    maxFunding: schemeTrans.maxFunding || scheme.maxFunding,
    potentialBenefit: schemeTrans.potentialBenefit || scheme.potentialBenefit,
    subsidyRate: schemeTrans.subsidyRate || scheme.subsidyRate,
    marginMoney: schemeTrans.marginMoney || scheme.marginMoney,
    description: schemeTrans.description || scheme.description,
    whyMatchedReasons: schemeTrans.whyMatchedReasons && schemeTrans.whyMatchedReasons.length > 0
      ? schemeTrans.whyMatchedReasons
      : scheme.whyMatchedReasons,
    requiredDocuments: schemeTrans.requiredDocuments && schemeTrans.requiredDocuments.length > 0
      ? schemeTrans.requiredDocuments
      : scheme.requiredDocuments
  };
}
