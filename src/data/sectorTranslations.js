export function getLocalizedSector(sector, langCode = 'en') {
  if (!sector) return sector;
  if (!langCode || langCode === 'en') return sector;
  const match = SECTOR_TRANSLATIONS[sector];
  if (match && match[langCode]) {
    return match[langCode];
  }
  return sector;
}

