export function getLocalizedDocument(docItem, langCode = 'en') {
  if (!docItem) return docItem;
  const langDict = DOCUMENT_TRANSLATIONS[langCode] || DOCUMENT_TRANSLATIONS.en;
  const trans = langDict[docItem.id] || DOCUMENT_TRANSLATIONS.en[docItem.id] || {};
  return {
    ...docItem,
    title: trans.title || docItem.title,
    category: trans.category || docItem.category,
    description: trans.description || docItem.description
  };
}
